function pushShed(push, id, x0, x1, zS, zN, ySouth, pitch, finish) {
  const slices = 10;
  const t = 0.08;
  for (let i = 0; i < slices; i++) {
    const z0 = zS + ((zN - zS) * i) / slices;
    const z1 = zS + ((zN - zS) * (i + 1)) / slices;
    const y0 = ySouth - pitch * (z0 - zS);
    const y1 = ySouth - pitch * (z1 - zS);
    const y = (y0 + y1) / 2 - t / 2;
    push(`${id}-${i}`, (x0 + x1) / 2, y, (z0 + z1) / 2, Math.abs(x1 - x0), t, Math.abs(z1 - z0) + 0.02, finish);
  }
}

