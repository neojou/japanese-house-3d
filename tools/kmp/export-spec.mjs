/**
 * Read-only export of the npm house spec into shared Kotlin.
 * Does not write src/, public/, package.json, or TASKS.md.
 *
 *   node tools/kmp/export-spec.mjs
 */
import { createServer } from "vite";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const outFile = resolve(
  root,
  "shared/src/commonMain/kotlin/com/neojou/japanesehouse3d/domain/HouseSpec.kt",
);
const interactFile = resolve(
  root,
  "shared/src/commonMain/kotlin/com/neojou/japanesehouse3d/domain/HouseInteract.kt",
);
const interactOnly = process.argv.includes("--interact-only");

const vite = await createServer({
  configFile: resolve(root, "vite.config.ts"),
  server: { middlewareMode: true },
  appType: "custom",
});

try {
  const dims = await vite.ssrLoadModule("/src/data/dimensions.ts");
  const height = await vite.ssrLoadModule("/src/lib/height.ts");
  const mats = await vite.ssrLoadModule("/src/lib/houseMaterials.ts");
  const ub = await vite.ssrLoadModule("/src/lib/ubBathHero.ts");
  const louver = await vite.ssrLoadModule("/src/lib/ubLouver.ts");
  const tubWater = await vite.ssrLoadModule("/src/lib/tubWater.ts");
  if (interactOnly) {
    writeFileSync(interactFile, renderInteract(dims, ub, louver, tubWater));
    console.log("wrote", interactFile);
  } else {
    writeFileSync(outFile, render(dims, height, mats, ub, louver));
    console.log("wrote", outFile);
  }
} finally {
  await vite.close();
}

