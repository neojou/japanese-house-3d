function swingKt(s) {
  return `        Swing("${s.id}", "${s.leafId}", "${s.axis}", "${s.hingeAt}", ${s.openSign}, ${num(s.openAngleDeg)}, ${num(s.hingeX)}, ${num(s.hingeY)}, ${num(s.hingeZ)}, ${num(s.centerX)}, ${num(s.centerY)}, ${num(s.centerZ)}, ${num(s.sizeX)}, ${num(s.sizeY)}, ${num(s.sizeZ)})`;
}

function slideKt(s) {
  return `        Slide("${s.id}", "${s.axis}", ${s.overlap}, ${s.panels}, ${num(s.stack)}, ${num(s.pocketA)}, ${num(s.pocketB)}, "${s.leafA}", "${s.leafB}")`;
}

function foldKt(s) {
  return `        Fold("${s.id}", "${s.leafId}", "${s.axis}", "${s.hingeAt}", ${s.openSign}, ${num(s.openAngleDeg)}, ${num(s.hingeX)}, ${num(s.hingeY)}, ${num(s.hingeZ)}, ${num(s.panelW)}, ${num(s.leafW)}, ${num(s.leafH)}, ${num(s.thick)})`;
}

function animatedIds(swings, slides, folds) {
  const ids = [];
  for (const s of swings) ids.push(s.leafId);
  for (const s of slides) {
    ids.push(s.leafA);
    if (s.panels === 2) ids.push(s.leafB);
  }
  for (const s of folds) ids.push(s.leafId);
  return ids;
}

