function solidPieces(wall, d) {
  const wallHeight = wall.height ?? d.storyWallHeight(wall.floor);
  const baseY = d.FLOOR_LEVELS[wall.floor];
  const openings = wall.openings ?? [];
  const alongX = wall.lengthX >= wall.lengthZ;
  if (openings.length === 0) {
    return [{
      key: wall.id,
      x: wall.x,
      y: baseY + wallHeight / 2,
      z: wall.z,
      sizeX: wall.lengthX,
      sizeY: wallHeight,
      sizeZ: wall.lengthZ,
    }];
  }
  const sorted = [...openings].sort((a, b) => a.fromStart - b.fromStart);
  const length = alongX ? wall.lengthX : wall.lengthZ;
  const thickness = alongX ? wall.lengthZ : wall.lengthX;
  const startCoord = alongX ? wall.x - wall.lengthX / 2 : wall.z - wall.lengthZ / 2;
  const pieces = [];
  let cursor = 0;
  const pushFull = (from, to, key) => {
    const segLen = to - from;
    if (segLen < 0.01) return;
    const mid = startCoord + (from + to) / 2;
    pieces.push({
      key,
      x: alongX ? mid : wall.x,
      y: baseY + wallHeight / 2,
      z: alongX ? wall.z : mid,
      sizeX: alongX ? segLen : thickness,
      sizeY: wallHeight,
      sizeZ: alongX ? thickness : segLen,
    });
  };
  const pushBand = (opening, y0, y1, key) => {
    const h = y1 - y0;
    if (h < 0.01) return;
    const mid = startCoord + opening.fromStart + opening.width / 2;
    pieces.push({
      key,
      x: alongX ? mid : wall.x,
      y: baseY + (y0 + y1) / 2,
      z: alongX ? wall.z : mid,
      sizeX: alongX ? opening.width : thickness,
      sizeY: h,
      sizeZ: alongX ? thickness : opening.width,
    });
  };
  sorted.forEach((opening, i) => {
    const a = Math.max(0, Math.min(length, opening.fromStart));
    const b = Math.max(0, Math.min(length, opening.fromStart + opening.width));
    pushFull(cursor, a, `${wall.id}-solid-${i}`);
    const sill = opening.sill ?? 0;
    const openTop = sill + opening.height;
    pushBand(opening, 0, sill, `${wall.id}-sill-${i}`);
    pushBand(opening, openTop, wallHeight, `${wall.id}-lintel-${i}`);
    cursor = Math.max(cursor, b);
  });
  pushFull(cursor, length, `${wall.id}-solid-end`);
  return pieces;
}

function pushFlight(push, flight, d) {
  const alongX = flight.direction === "east" || flight.direction === "west";
  const sign = flight.direction === "south" || flight.direction === "west" ? -1 : 1;
  for (let i = 0; i < flight.stepCount; i++) {
    const along = (i + 0.5) * flight.treadDepth * sign;
    const x = flight.x + (alongX ? along : 0);
    const z = flight.z + (alongX ? 0 : along);
    const y = flight.baseY + (i + 0.5) * flight.riserHeight;
    const sizeX = alongX ? flight.treadDepth : flight.width;
    const sizeZ = alongX ? flight.width : flight.treadDepth;
    push(`${flight.id}-step-${i}`, x, y, z, sizeX, flight.riserHeight, sizeZ, "stair");
  }
}

function pushWinder(push, winder) {
  const n = winder.stepCount;
  const rMid = (winder.rInner + winder.rOuter) / 2;
  const radial = winder.rOuter - winder.rInner;
  const dAng = winder.sweep / n;
  for (let i = 0; i < n; i++) {
    const aMid = winder.startAngle + (i + 0.5) * dAng;
    const x = winder.pivotX + rMid * Math.cos(aMid);
    const z = winder.pivotZ + rMid * Math.sin(aMid);
    const y = winder.baseY + (i + 0.5) * winder.riserHeight;
    const chord = Math.abs(rMid * dAng) * 1.05;
    const yaw = -(aMid + Math.PI / 2);
    push(`${winder.id}-w-${i}`, x, y, z, chord, winder.riserHeight, radial, "stair", yaw);
  }
}

function pushDoors(push, d) {
  const T = d.BUILDING.wallThickness;
  const FRAME = 0.05;
  const LEAF_T = 0.04;
  for (const def of d.SWING_DOORS) {
    const leafW = Math.abs(def.alongMax - def.alongMin) - 0.02;
    const leafH = def.height - FRAME - 0.01;
    const baseY = d.FLOOR_LEVELS[def.floor ?? "1f"];
    const sillY = baseY + def.sill;
    const hingeAlong = def.hingeAt === "min" ? def.alongMin : def.alongMax;
    const leafDir = def.hingeAt === "min" ? 1 : -1;
    const midY = sillY + leafH / 2;
    const oak = def.leaf ? "doorOak" : "door";
    const frame = def.leaf ? "doorOak" : "doorFrame";
    if (def.axis === "ew") {
      push(`${def.id}-post-a`, def.alongMin + FRAME / 2, sillY + def.height / 2, def.wallZ, FRAME, def.height, T, frame);
      push(`${def.id}-post-b`, def.alongMax - FRAME / 2, sillY + def.height / 2, def.wallZ, FRAME, def.height, T, frame);
      push(`${def.id}-head`, (def.alongMin + def.alongMax) / 2, sillY + def.height - FRAME / 2, def.wallZ, leafW + 0.02, FRAME, T, frame);
      push(`${def.id}-leaf`, hingeAlong + leafDir * leafW / 2, midY, def.wallZ, leafW, leafH, LEAF_T, oak);
    } else {
      push(`${def.id}-post-a`, def.wallX, sillY + def.height / 2, def.alongMin + FRAME / 2, T, def.height, FRAME, frame);
      push(`${def.id}-post-b`, def.wallX, sillY + def.height / 2, def.alongMax - FRAME / 2, T, def.height, FRAME, frame);
      push(`${def.id}-head`, def.wallX, sillY + def.height - FRAME / 2, (def.alongMin + def.alongMax) / 2, T, FRAME, leafW + 0.02, frame);
      push(`${def.id}-leaf`, def.wallX, midY, hingeAlong + leafDir * leafW / 2, LEAF_T, leafH, leafW, oak);
    }
  }
  for (const def of d.SLIDE_DOORS) {
    const openingW = Math.abs(def.alongMax - def.alongMin);
    const n = def.panels;
    const overlap = 0.04;
    const leafW = n === 2 ? (openingW + overlap) / 2 + 0.01 : openingW - 0.02;
    const leafH = def.height - 0.04;
    const baseY = d.FLOOR_LEVELS[def.floor ?? "1f"];
    const sillY = baseY + def.sill;
    const closedA = n === 2 ? def.alongMin + leafW / 2 - overlap * 0.25 : (def.alongMin + def.alongMax) / 2;
    const closedB = n === 2 ? def.alongMax - leafW / 2 + overlap * 0.25 : closedA;
    const frame = def.leaf ? "doorOak" : "doorFrame";
    const leafFinish = def.leaf ? "doorOak" : "glass";
    const y = sillY + 0.02 + leafH / 2;
    const thick = def.leaf ? 0.04 : 0.012;
    if (def.axis === "ew") {
      push(`${def.id}-a`, closedA, y, def.wallZ, leafW, leafH, thick, leafFinish);
      if (n === 2) push(`${def.id}-b`, closedB, y, def.wallZ, leafW, leafH, thick, leafFinish);
      push(`${def.id}-post-a`, def.alongMin, sillY + def.height / 2, def.wallZ, 0.028, def.height, T * 0.95, frame);
      push(`${def.id}-post-b`, def.alongMax, sillY + def.height / 2, def.wallZ, 0.028, def.height, T * 0.95, frame);
    } else {
      push(`${def.id}-a`, def.wallX, y, closedA, thick, leafH, leafW, leafFinish);
      if (n === 2) push(`${def.id}-b`, def.wallX, y, closedB, thick, leafH, leafW, leafFinish);
      push(`${def.id}-post-a`, def.wallX, sillY + def.height / 2, def.alongMin, T * 0.95, def.height, 0.028, frame);
      push(`${def.id}-post-b`, def.wallX, sillY + def.height / 2, def.alongMax, T * 0.95, def.height, 0.028, frame);
    }
  }
  for (const def of d.FOLD_DOORS) {
    const openingW = Math.abs(def.alongMax - def.alongMin);
    const baseY = d.FLOOR_LEVELS[def.floor ?? "1f"];
    const sillY = baseY + def.sill;
    const mid = (def.alongMin + def.alongMax) / 2;
    const leafH = def.height - 0.045;
    if (def.axis === "ew") {
      push(`${def.id}-leaf`, mid, sillY + leafH / 2, def.wallZ, openingW - 0.04, leafH, 0.04, "doorOak");
    } else {
      push(`${def.id}-leaf`, def.wallX, sillY + leafH / 2, mid, 0.04, leafH, openingW - 0.04, "doorOak");
    }
  }
}

function pushSite(push, d) {
  const g = d.GENKAN_ENTRY;
  const y0 = d.FLOOR_LEVELS["1f"];
  const p = d.PARKING_1F;
  push(
    "ground",
    d.BUILDING.width / 2,
    -0.08,
    d.BUILDING.depth / 2,
    d.BUILDING.width + 16,
    0.12,
    d.BUILDING.depth + 16,
    "ground",
  );
  push(
    "parking",
    p.x + p.width / 2,
    y0 - 0.01,
    p.z + p.depth / 2,
    p.width,
    0.02,
    p.depth,
    "parking",
  );
  const midX = (g.x0 + g.x1) / 2;
  const face = g.z - d.BUILDING.wallThickness / 2;
  for (let i = 0; i < g.stepCount; i++) {
    const level = i + 1;
    const topY = g.stepHeight * level;
    const centerY = topY - g.stepHeight / 2;
    const fromDoor = g.stepCount - i;
    const centerZ = face - g.stepDepth * (fromDoor - 0.5);
    push(`genkan-step-${i}`, midX, y0 + centerY, centerZ, g.stepWidth, g.stepHeight, g.stepDepth, "step");
  }
}

