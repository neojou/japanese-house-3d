    const i = Math.floor(flight.stepCount / 2);
    let x = flight.x;
    let z = flight.z;
    const along = (i + 0.5) * flight.treadDepth;
    if (flight.direction === "north") z += along;
    else if (flight.direction === "south") z -= along;
    else if (flight.direction === "east") x += along;
